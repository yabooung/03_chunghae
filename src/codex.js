/* ─────────── 지금 판에서 만족한 조건 ─────────── */
function scan(S) { const T = new Set(['start']); if (!S) return T;
  const add = t => T.add(t), keys = o => Object.keys(o || {});
  if (S.cap) add('cap:' + S.cap);
  for (const k of keys(S.docked)) add('port:' + k);
  for (const k of keys(S.ledger)) { const L = S.ledger[k]; for (const id of keys(L && L.p)) add('good:' + id); for (const id of keys(L && L.b)) add('good:' + id); }
  for (const s of (S.slots || []).concat(S.store || [])) add('good:' + s.id);
  for (const f of keys(S.found)) add('find:' + f);
  for (const m of (S.mates || [])) add('mate:' + m);
  for (const k of keys(S.taverns)) for (const m of ((S.taverns[k] || {}).offer || [])) if (S.docked && S.docked[k]) add('mate:' + m);
  for (const c of (S.crew || [])) { add('crew:' + c.k); if (c.asked) add('ask:' + c.k); }
  for (const b of keys(S.beaten)) add('boss:' + b);
  if (S.bounty && S.bounty.id) add('boss:' + S.bounty.id);
  for (const k of keys(S.bOffers)) { const o = S.bOffers[k]; if (o && o.id && S.docked && S.docked[k]) add('boss:' + o.id); }
  for (const q of keys(S.quests)) add('quest:' + q);
  if (S.main && S.cap) { const a = S.main.act | 0; for (let i = 0; i < a; i++) add(`act:${S.cap}:${i}`); if (S.main.started) add(`act:${S.cap}:${a}`); for (const f of keys(S.main.flags)) add('flag:' + f); }
  for (const r of keys(S.relics)) add('relic:' + r);
  for (const n of (S.news || [])) add('news:' + n.id);
  for (let i = 1; i <= (S.tier | 0); i++) add('ship:' + i);
  if (S.stats && S.stats.voyages) add('voyage');
  if (S.ending) add('ending:' + S.ending);
  return T; }

/* 화면에서만 보이는 것(항해 사건·이야기 장면·해전 상대)은 ui가 core의 출력을 넘겨 기록한다 */
function feedOut(state, outs) { for (const o of outs || []) {
  if (o.type === 'event' && o.ev) mark(state, 'ev:' + o.ev.id);
  if (o.type === 'news' && o.news) mark(state, 'news:' + o.news.id);
  if (o.type === 'arrive' && o.info && ((o.info.race || []).length || (o.info.rivalHere || []).length)) mark(state, 'rival'); } }
function mark(state, t) { if (!state.seen) state.seen = {}; state.seen[t] = 1; }
function blank() { return { u: {}, n: {}, seen: {} }; }
/* 옛 메타(사전 없음)나 깨진 값도 받는다 */
function norm(x) { const s = blank(); if (x && typeof x === 'object') for (const k of ['u', 'n', 'seen']) if (x[k] && typeof x[k] === 'object') for (const id of Object.keys(x[k])) if (k === 'seen' || BY[id]) s[k][id] = 1; return s; }

/* 새로 열린 항목 id 목록을 돌려주고 state에 남긴다(한 번 열리면 판이 바뀌어도 남는다) */
function check(state, S) { const T = scan(S); for (const t of Object.keys(state.seen || {})) T.add(t); const fresh = [];
  for (const e of ENTRIES) if (!state.u[e.id] && e.on.some(t => T.has(t))) { state.u[e.id] = 1; state.n[e.id] = 1; fresh.push(e.id); }
  return fresh; }
const isOpen = (state, id) => !!(state && state.u[id]);
function count(state, cat) { const es = cat ? ENTRIES.filter(e => e.cat === cat) : ENTRIES; return { n: es.filter(e => state.u[e.id]).length, m: es.length }; }

/* 잠긴 항목의 귀띔 — 첫 조건으로 */
const ACTN = ['첫', '둘째', '셋째', '넷째', '다섯째'];

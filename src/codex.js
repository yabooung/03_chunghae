const hint = e => hintOf(e.on[0]);

/* 글 속 낱말 → 항목. 열린 항목만, 긴 낱말부터 */
function terms(state) { const out = [];
  for (const e of ENTRIES) if (state.u[e.id]) for (const t of e.terms) if (t && t.length >= 2) out.push([t, e.id]);
  return out.sort((a, b) => b[0].length - a[0].length); }

/* 찾기 — 열린 항목만. 이름·한자·낱말이 먼저, 그다음 한 줄·본문 */
function search(state, q) { q = String(q || '').trim().toLowerCase(); if (!q) return [];
  const hit = (s) => String(s || '').toLowerCase().includes(q); const out = [];
  for (const e of ENTRIES) { if (!state.u[e.id]) continue;
    const r = hit(e.title) || hit(e.hanja) || e.terms.some(hit) ? 3 : hit(e.sum) ? 2 : [...e.hist, e.game, e.debate || ''].some(hit) ? 1 : 0;
    if (r) out.push([r, e]); }
  return out.sort((a, b) => b[0] - a[0]).map(x => x[1]); }

/* 알고 있었나요? — 열린 항목 가운데 하나 (없으면 처음부터 아는 것에서) */
function fact(state, rnd) { rnd = rnd || Math.random; let pool = ENTRIES.filter(e => e.fact && state && state.u[e.id]); if (!pool.length) pool = ENTRIES.filter(e => e.fact && e.on.includes('start'));
  return pool.length ? pool[Math.floor(rnd() * pool.length)] : null; }

return { CATS, ENTRIES, BY, WHO, portEntry, goodEntry, scan, feedOut, mark, blank, norm, check, isOpen, count, hint, hintOf, terms, search, fact };
